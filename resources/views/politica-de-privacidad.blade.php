                    <h2>2. A quién aplica esta política</h2>
                    <p>Según tu relación con la Plataforma, tratamos distintos tipos de datos:</p>
                    <ul>
                        <li><strong>Dueños y empleados de un negocio:</strong> nombre, correo, teléfono y contraseña (cifrada) para acceder a su panel de administración.</li>
                        <li><strong>Clientes finales de un negocio</strong> (quienes reservan una cita, curso o producto): nombre, celular, correo electrónico (opcional) y notas que dejes al reservar.</li>
                        <li><strong>Pacientes de un spa con historia clínica:</strong> además de lo anterior, datos de salud propios del servicio recibido y tu firma digital, tratados como datos sensibles con medidas de seguridad reforzadas (ver sección 5).</li>
                    </ul>

                    <h2>3. Finalidad del tratamiento</h2>
                    <p>Usamos tus datos personales para:</p>
                    <ul>
                        <li>Crear y administrar tu cuenta y la de tu negocio en la Plataforma.</li>
                        <li>Procesar, confirmar y recordar tus citas, cursos o pedidos.</li>
                        <li>Enviarte notificaciones por correo electrónico relacionadas con tus reservas (confirmación, recordatorio, cancelación).</li>
                        <li>Permitir que el negocio con el que reservas lleve tu historial de servicios y, si aplica, tu historia clínica.</li>
                        <li>Cumplir obligaciones legales y atender requerimientos de autoridades competentes.</li>
                        <li>Mejorar la seguridad y el funcionamiento de la Plataforma.</li>
                    </ul>
                    <p>No usamos tus datos personales con fines publicitarios ni los vendemos a terceros.</p>

                    <h2>4. Autorización</h2>
                    <p>
                        Al marcar la casilla de autorización en el formulario de reserva, o al crear una cuenta en la
                        Plataforma, aceptas el tratamiento de tus datos personales conforme a esta política. Si no
                        estás de acuerdo, puedes optar por no completar el formulario o contactar directamente al
                        negocio por otro medio.
                    </p>

                    <h2>5. Datos sensibles e historia clínica</h2>
                    <p>
                        Cuando un negocio de tipo spa habilita historia clínica, los datos de salud que allí se registran
                        (incluida tu firma digital) se consideran datos sensibles bajo la ley colombiana. Estos datos:
                    </p>
                    <ul>
                        <li>Nunca se exponen por una URL pública; solo son accesibles mediante rutas autenticadas, exclusivamente para el negocio que te atendió y para ti.</li>
                        <li>No son usados para ningún fin distinto al clínico/asistencial del propio negocio.</li>
                        <li>Se almacenan en un disco privado del servidor, nunca en el almacenamiento público del sitio.</li>
                    </ul>

                    <h2>6. Encargados del tratamiento y terceros</h2>
                    <p>Para operar la Plataforma, compartimos información estrictamente necesaria con:</p>
                    <ul>
                        <li>Nuestro proveedor de hospedaje e infraestructura, para almacenar la base de datos y los archivos.</li>
                        <li>Nuestro proveedor de correo electrónico, para el envío de confirmaciones y recordatorios.</li>
                        <li>Google, únicamente si decides iniciar sesión o vincular tu cuenta de Google, y solo para identificarte (nombre y correo) — nunca accedemos a tu Calendario, Gmail ni otros datos de Google.</li>
                    </ul>
                    <p>No transferimos tus datos personales a terceros con fines comerciales.</p>

                    <h2>7. Tus derechos como titular de los datos</h2>
                    <p>Conforme a la Ley 1581 de 2012, tienes derecho a:</p>
                    <ul>
                        <li>Conocer, actualizar y rectificar tus datos personales.</li>
                        <li>Solicitar prueba de la autorización otorgada.</li>
                        <li>Ser informado sobre el uso dado a tus datos.</li>
                        <li>Presentar quejas ante la Superintendencia de Industria y Comercio (SIC) por infracciones a la ley.</li>
                        <li>Revocar la autorización y/o solicitar la supresión de tus datos, cuando no exista un deber legal o contractual que lo impida.</li>
                        <li>Acceder de forma gratuita a tus datos personales.</li>
                    </ul>
                    <p>
                        Para ejercer cualquiera de estos derechos, escríbenos a
                        <a class="text-primario underline" href="mailto:notificaciones@marintech.site">notificaciones@marintech.site</a>
                        indicando tu solicitud y los datos que permitan identificarte. Responderemos dentro de los
                        términos establecidos por la ley colombiana.
                    </p>

                    <h2>8. Seguridad de la información</h2>
                    <p>
                        Aplicamos medidas técnicas y organizativas razonables para proteger tus datos personales contra
                        pérdida, uso indebido, acceso no autorizado o divulgación, incluyendo cifrado de contraseñas,
                        control de acceso por negocio (cada negocio solo puede ver y modificar su propia información) y
                        registro de auditoría de cambios sensibles.
                    </p>

                    <h2>9. Tiempo de conservación</h2>
                    <p>
                        Conservamos tus datos personales mientras tu cuenta o la del negocio esté activa, y por el
                        tiempo adicional que exija la ley o que sea razonable para fines históricos, estadísticos o de
                        seguridad. Si un negocio es cancelado, sus datos se conservan por un periodo limitado antes de
                        su eliminación definitiva, conforme a la configuración de retención de cada negocio.
                    </p>

